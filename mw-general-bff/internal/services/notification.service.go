package services

import (
	"context"
	pb "mw-general-bff/pkg/grpcAutoGenerated/notification"
)

type NotificationService struct {
	notificationGRPC        pb.NotificationServiceClient
	notificationSettingGRPC pb.NotificationSettingServiceClient
}

func newNotificationService(
	notificationGRPC pb.NotificationServiceClient,
	notificationSettingGRPC pb.NotificationSettingServiceClient,
) *NotificationService {
	return &NotificationService{notificationGRPC, notificationSettingGRPC}
}

type Nature string

const (
	PrivateChat      Nature = "private_chat"
	GroupChat        Nature = "group_chat"
	OwnWay           Nature = "own_way"
	MentoringWay     Nature = "mentoring_way"
	MentoringRequest Nature = "mentoring_request"
	FavoriteWay      Nature = "favorite_way"
)

func (ns *NotificationService) CreateNotifications(ctx context.Context, params *pb.CreateNotificationRequest) (*pb.CreateNotificationsResponse, error) {
	createNotificationsResponseRaw, err := ns.notificationGRPC.CreateNotifications(ctx, params)
	if err != nil {
		return nil, err
	}

	return createNotificationsResponseRaw, nil
}

func (ns *NotificationService) CreateNotificationSettings(ctx context.Context, userUUID string) error {
	in := &pb.CreateNotificationSettingsRequest{
		UserUuid: userUUID,
	}

	_, err := ns.notificationSettingGRPC.CreateNotificationSettings(ctx, in)
	if err != nil {
		return err
	}

	return nil
}

func (ns *NotificationService) GetNotificationList(ctx context.Context, userUUID string, page, limit int32, isOnlyNew bool) (*pb.GetNotificationListResponse, error) {
	return ns.notificationGRPC.GetNotificationList(ctx, &pb.GetNotificationListRequest{
		UserUuid:  userUUID,
		Page:      page,
		Limit:     limit,
		IsOnlyNew: isOnlyNew,
	})
}

func (ns *NotificationService) UpdateNotification(ctx context.Context, notificationUUID string, isRead bool) (*pb.Notification, error) {
	return ns.notificationGRPC.UpdateNotification(ctx, &pb.UpdateNotificationRequest{
		NotificationUuid: notificationUUID,
		IsRead:          isRead,
	})
}

func (ns *NotificationService) GetNotificationSettingList(ctx context.Context, userUUID string) (*pb.GetNotificationSettingListResponse, error) {
	return ns.notificationSettingGRPC.GetNotificationSettingList(ctx, &pb.GetNotificationSettingListRequest{
		UserUuid: userUUID,
	})
}

func (ns *NotificationService) UpdateNotificationSetting(ctx context.Context, notificationSettingUUID string, isEnabled bool) (*pb.NotificationSettingResponse, error) {
	return ns.notificationSettingGRPC.UpdateNotificationSetting(ctx, &pb.UpdateNotificationSettingRequest{
		NotificationSettingUuid: notificationSettingUUID,
		IsEnabled:               isEnabled,
	})
}
