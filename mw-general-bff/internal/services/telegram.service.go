package services

import (
	"context"
	"fmt"

	telegrambot "mw-general-bff/pkg/grpcAutoGenerated/telegram-bot"

	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
)

type TelegramService struct {
	telegramGRPC telegrambot.TelegramServiceClient
}

func newTelegramService(telegramGRPC telegrambot.TelegramServiceClient) *TelegramService {
	return &TelegramService{telegramGRPC: telegramGRPC}
}

func (ts *TelegramService) SendTelegramNotificationToUser(ctx context.Context, userUuid string, message string) error {
	req := &telegrambot.SendTelegramNotificationRequest{
		UserUuid: userUuid,
		Message:  message,
	}

	_, err := ts.telegramGRPC.SendTelegramNotification(ctx, req)
	if err != nil {
		return fmt.Errorf("failed to send telegram notification: %w", err)
	}

	return nil
}

func (ts *TelegramService) GetUserTelegramChatID(ctx context.Context, userUuid string) (int64, error) {
	req := &telegrambot.GetUserTelegramChatIdRequest{
		UserUuid: userUuid,
	}

	resp, err := ts.telegramGRPC.GetUserTelegramChatId(ctx, req)
	if err != nil {
		st, _ := status.FromError(err)
		if st.Code() == codes.NotFound {
			return 0, fmt.Errorf("user has no telegram chat ID")
		}
		return 0, fmt.Errorf("failed to get telegram chat ID: %w", err)
	}

	return resp.TelegramChatId, nil
}