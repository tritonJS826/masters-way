package facades

import (
	"context"
	"mw-general-bff/internal/schemas"
	"mw-general-bff/internal/services"
	pb "mw-general-bff/pkg/grpcAutoGenerated/notification"

	"github.com/samber/lo"
)

type NotificationFacade struct {
	notificationService *services.NotificationService
}

func newNotificationFacade(notificationService *services.NotificationService) *NotificationFacade {
	return &NotificationFacade{notificationService}
}

func (nf *NotificationFacade) GetNotificationList(ctx context.Context, userUUID string, page, limit int32, isOnlyNew bool) (*schemas.GetNotificationListResponse, error) {
	notificationListRaw, err := nf.notificationService.GetNotificationList(ctx, userUUID, page, limit, isOnlyNew)
	if err != nil {
		return nil, err
	}

	notificationList := lo.Map(notificationListRaw.Notifications, func(notificationRaw *pb.Notification, i int) schemas.NotificationResponse {
		return schemas.NotificationResponse{
			UUID:        notificationRaw.Uuid,
			UserUUID:    notificationRaw.UserUuid,
			IsRead:      notificationRaw.IsRead,
			Description: notificationRaw.Description,
			Url:         notificationRaw.Url,
			Nature:      notificationRaw.Nature.String(),
			CreatedAt:   notificationRaw.CreatedAt,
		}
	})

	return &schemas.GetNotificationListResponse{
		Size:          int(notificationListRaw.TotalSize),
		Notifications: notificationList,
	}, nil
}

func (nf *NotificationFacade) UpdateNotification(ctx context.Context, notificationUUID string, isRead bool) (*schemas.NotificationResponse, error) {
	notification, err := nf.notificationService.UpdateNotification(ctx, notificationUUID, isRead)
	if err != nil {
		return nil, err
	}

	return &schemas.NotificationResponse{
		UUID:        notification.Uuid,
		UserUUID:    notification.UserUuid,
		IsRead:      notification.IsRead,
		Description: notification.Description,
		Url:         notification.Url,
		Nature:      notification.Nature.String(),
		CreatedAt:   notification.CreatedAt,
	}, nil
}

func (nf *NotificationFacade) GetNotificationSettingList(ctx context.Context, userUUID string) (*schemas.GetNotificationSettingListResponse, error) {
	notificationSettingListRaw, err := nf.notificationService.GetNotificationSettingList(ctx, userUUID)
	if err != nil {
		return nil, err
	}

	notificationSettingList := lo.Map(notificationSettingListRaw.NotificationSettings, func(notificationSettingRaw *pb.NotificationSettingResponse, _ int) schemas.NotificationSettingResponse {
		return schemas.NotificationSettingResponse{
			UUID:      notificationSettingRaw.Uuid,
			UserUUID:  notificationSettingRaw.UserUuid,
			Nature:    notificationSettingRaw.Nature.String(),
			Channel:   notificationSettingRaw.Channel.String(),
			IsEnabled: notificationSettingRaw.IsEnabled,
		}
	})

	return &schemas.GetNotificationSettingListResponse{
		NotificationSettings: notificationSettingList,
	}, nil
}

func (nf *NotificationFacade) UpdateNotificationSetting(ctx context.Context, notificationSettingID string, isEnabled bool) (*schemas.NotificationSettingResponse, error) {
	notificationSetting, err := nf.notificationService.UpdateNotificationSetting(ctx, notificationSettingID, isEnabled)
	if err != nil {
		return nil, err
	}

	return &schemas.NotificationSettingResponse{
		UUID:      notificationSetting.Uuid,
		UserUUID:  notificationSetting.UserUuid,
		Nature:    notificationSetting.Nature.String(),
		Channel:   notificationSetting.Channel.String(),
		IsEnabled: notificationSetting.IsEnabled,
	}, nil
}